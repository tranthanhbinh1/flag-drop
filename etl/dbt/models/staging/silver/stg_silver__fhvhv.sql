-- FHVHV trips as Silver publishes them, plus `service`. Names follow yellow where the meaning is the
-- same (fare_amount, tip_amount, tolls_amount) so intermediate/ can union the services column for column.
select
    'fhvhv' as service,
    hvfhs_license_num,
    dispatching_base_num,
    originating_base_num,
    request_ts,
    on_scene_ts,
    pickup_ts,
    dropoff_ts,
    pickup_location_id,
    dropoff_location_id,
    trip_miles,
    trip_time_sec,
    base_passenger_fare as fare_amount,
    tolls as tolls_amount,
    bcf,
    sales_tax,
    congestion_surcharge,
    airport_fee,
    cbd_congestion_fee,
    tips as tip_amount,
    driver_pay,
    shared_request,
    shared_match,
    access_a_ride,
    wav_request,
    wav_match,
    trip_duration_min,
    is_non_positive_duration,
    is_non_positive_fare,
    is_out_of_period,
    is_valid_trip,
    source_month,
    source_file,
    schema_version,
    ingested_at
from {{ source('silver', 'fhvhv') }}
