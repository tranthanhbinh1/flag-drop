-- Yellow trips as Silver publishes them, plus `service`. Thin on purpose: schema versions, codes and
-- flags were settled in Silver; anything joined or derived belongs in intermediate/ and marts/.
select
    'yellow' as service,
    vendor_id,
    pickup_ts,
    dropoff_ts,
    passenger_count,
    trip_distance as trip_miles,
    rate_code_id,
    store_and_fwd,
    payment_type,
    pickup_location_id,
    dropoff_location_id,
    pickup_longitude,
    pickup_latitude,
    dropoff_longitude,
    dropoff_latitude,
    fare_amount,
    extra,
    mta_tax,
    tip_amount,
    tolls_amount,
    improvement_surcharge,
    congestion_surcharge,
    airport_fee,
    cbd_congestion_fee,
    total_amount,
    request_source,
    trip_duration_min,
    is_non_positive_duration,
    is_non_positive_fare,
    is_out_of_period,
    is_passenger_count_invalid,
    is_valid_trip,
    source_month,
    source_file,
    schema_version,
    ingested_at
from {{ source('silver', 'yellow') }}
